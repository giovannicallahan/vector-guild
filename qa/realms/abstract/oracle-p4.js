const run = (tables, p) => tables.reduce((x, t) => t[x], p);
/* The permutation of all marks made by a list of tables (first move first). */
const perm = (tables, m) => Array.from({ length: m }, (_, p) => run(tables, p));
const cyclesOf = pm => {
  const seen = new Array(pm.length).fill(false), lens = [];
  for (let s = 0; s < pm.length; s++) if (!seen[s]) { let x = s, len = 0; while (!seen[x]) { seen[x] = true; x = pm[x]; len++; } lens.push(len); }
  return lens;
};
const gcd = (a, b) => { while (b) [a, b] = [b, a % b]; return a; };
